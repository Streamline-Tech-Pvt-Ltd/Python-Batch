# Slicing: Slicing is used to access a range of a string, list, or tuple.It allows you to access multiple elements at once.

# Syntax 
# sequence[start : stop : step]
# start → Starting index (included)
# stop → Ending index (One Value Before stop the end value)
# step → Increment/decrement value (Can be negative for reverse slicing)








